  function getLang() {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "zh" || saved === "en") return saved;
    return "en";
  }

  function setLang(lang) {
    localStorage.setItem(LANG_KEY, lang === "en" ? "en" : "zh");
  }

  function t(key, vars) {
    const lang = getLang();
    let text = (dict[lang] && dict[lang][key]) || (dict.zh && dict.zh[key]) || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, "g"), vars[k]);
      });
    }
    return text;
  }

  function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      el.textContent = t(key);
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (!key) return;
      el.setAttribute("placeholder", t(key));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (!key) return;
      el.setAttribute("aria-label", t(key));
    });
    const titleKey = document.body?.getAttribute("data-i18n-title");
    if (titleKey) document.title = t(titleKey);
    document.documentElement.lang = getLang() === "en" ? "en" : "zh-CN";
  }

  function localizeField(field) {
    if (field == null) return "";
    if (typeof field === "string") return field;
    const lang = getLang();
    return field[lang] || field.zh || field.en || "";
  }

  function localizeList(list) {
    if (!Array.isArray(list)) return [];
    return list.map((item) => {
      if (typeof item === "string") return item;
      if (Array.isArray(item)) return item.map(localizeField);
      return localizeField(item);
    });
  }

  function formatMoney(n) {
    const v = Number(n);
    return (Number.isFinite(v) ? v : 0).toFixed(2);
  }

  function money(n) {
    return "$" + formatMoney(n);
  }

  window.I18N = { getLang, setLang, t, applyI18n, localizeField, localizeList, dict, formatMoney, money };

  function syncChromeOffset() {
    const topBar = document.querySelector(".top-bar");
    const header = document.querySelector("header");
    if (!topBar || !header || document.body.classList.contains("admin-body")) return;
    const topH = Math.ceil(topBar.getBoundingClientRect().height);
    const headH = Math.ceil(header.getBoundingClientRect().height);
    document.documentElement.style.setProperty("--topbar-offset", topH + "px");
    document.documentElement.style.setProperty("--header-offset", topH + headH + 8 + "px");
  }

  function initChromeOffset() {
    if (!document.querySelector(".top-bar") || !document.querySelector("header")) return;
    const run = () => requestAnimationFrame(syncChromeOffset);
    run();
    window.addEventListener("resize", run);
    window.addEventListener("orientationchange", run);
    if (window.visualViewport) visualViewport.addEventListener("resize", run);
    if (window.ResizeObserver) {
      const ro = new ResizeObserver(run);
      const header = document.querySelector("header");
      const topBar = document.querySelector(".top-bar");
      if (header) ro.observe(header);
      if (topBar) ro.observe(topBar);
    }
  }

  applyI18n();

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initChromeOffset);
  } else {
    initChromeOffset();
  }
